<?php

declare(strict_types=1);

/**
 * Development-only fake Gotenberg server.
 *
 * Usage (from the project root, note the ini flag so the raw multipart body is
 * available for inspection):
 *   php -d enable_post_data_reading=0 -S 127.0.0.1:3001 tools/dev/fake-gotenberg.php
 *
 * It implements the two endpoints the application uses so the full PDF
 * pipeline (render -> HTTP -> store -> download) can be exercised on a machine
 * where the real Gotenberg container is not running. It is NOT part of the
 * production application and must never be deployed to the server.
 */
ini_set('display_errors', '0');
error_reporting(E_ALL);

$uri = parse_url($_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH) ?: '/';

if ($uri === '/health') {
    respondJson(['status' => 'up', 'service' => 'fake-gotenberg']);
}

if ($uri === '/forms/chromium/convert/html' && ($_SERVER['REQUEST_METHOD'] ?? 'GET') === 'POST') {
    $logDir = dirname(__DIR__, 2).'/storage/app/tmp';

    if (! is_dir($logDir)) {
        @mkdir($logDir, 0775, true);
    }

    $raw = (string) file_get_contents('php://input');
    $parts = [];

    if (preg_match_all('/name="([^"]+)"(?:;\s*filename="([^"]+)")?/', $raw, $matches, PREG_SET_ORDER) !== false) {
        foreach ($matches as $match) {
            $parts[] = [
                'name' => $match[1] ?? null,
                'filename' => ($match[2] ?? '') !== '' ? $match[2] : null,
            ];
        }
    }

    $summary = [
        'time' => date('c'),
        'raw_body_size' => strlen($raw),
        'parts' => $parts,
        'has_index_html' => str_contains($raw, 'name="files"; filename="index.html"'),
        'has_header_html' => str_contains($raw, 'name="files"; filename="header.html"'),
        'has_footer_html' => str_contains($raw, 'name="files"; filename="footer.html"'),
        'has_persian_text' => (bool) preg_match('/[\x{0600}-\x{06FF}]/u', $raw),
        'has_asset_font' => str_contains($raw, 'vazirmatn-regular.woff2'),
        'has_unrendered_directive' => str_contains($raw, '@jdate') || str_contains($raw, '@foreach') || str_contains($raw, '{{ '),
        'fields' => $_POST,
    ];

    @file_put_contents($logDir.'/fake-gotenberg-last-request.json', json_encode($summary, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE));
    @file_put_contents($logDir.'/fake-gotenberg-last-request.multipart', $raw);

    header('Content-Type: application/pdf');
    header('Content-Length: '.strlen(mockPdf()));
    echo mockPdf();
    exit;
}

http_response_code(404);
respondJson(['status' => 'error', 'message' => 'Not found']);

function respondJson(array $payload, int $status = 200): never
{
    http_response_code($status);
    header('Content-Type: application/json');
    echo json_encode($payload);

    exit;
}

/**
 * Minimal syntactically valid one-page PDF used as a mock response.
 */
function mockPdf(): string
{
    static $pdf = null;

    if ($pdf !== null) {
        return $pdf;
    }

    $text = 'Central PDF Service - mock PDF generated by tools/dev/fake-gotenberg.php';

    $stream = "BT\n/F1 12 Tf\n72 720 Td\n(".$text.") Tj\nET\n";
    $objects = [];

    $objects[] = '<< /Type /Catalog /Pages 2 0 R >>';
    $objects[] = '<< /Type /Pages /Kids [3 0 R] /Count 1 >>';
    $objects[] = '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>';
    $objects[] = '<< /Length '.strlen($stream)." >>\nstream\n".$stream.'endstream';
    $objects[] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>';

    $pdf = "%PDF-1.4\n";
    $offsets = [];

    foreach ($objects as $index => $object) {
        $offsets[$index + 1] = strlen($pdf);
        $pdf .= ($index + 1)." 0 obj\n".$object."\nendobj\n";
    }

    $xrefOffset = strlen($pdf);
    $pdf .= "xref\n0 ".(count($objects) + 1)."\n0000000000 65535 f \n";

    foreach ($offsets as $offset) {
        $pdf .= sprintf("%010d 00000 n \n", $offset);
    }

    $pdf .= "trailer\n<< /Size ".(count($objects) + 1)." /Root 1 0 R >>\nstartxref\n".$xrefOffset."\n%%EOF\n";

    return $pdf;
}
